# Question 15: Write a program to demonstrate bitwise AND, OR and XOR operators.

a = 12  # Binary: 1100
b = 10  # Binary: 1010

print(f"a = {a} (bin: {bin(a)})")
print(f"b = {b} (bin: {bin(b)})")
print("a & b (AND):", a & b, f"(bin: {bin(a & b)})")
print("a | b (OR) :", a | b, f"(bin: {bin(a | b)})")
print("a ^ b (XOR):", a ^ b, f"(bin: {bin(a ^ b)})")
